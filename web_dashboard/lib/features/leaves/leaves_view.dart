enum DocumentType {
  image,
  pdf,
  word,
  text,
  legacyLocal,
  unknown,
}

DocumentType _detectDocType(String? url) {
  if (url == null || url.trim().isEmpty) return DocumentType.unknown;
  final raw = url.trim().toLowerCase();
  if (raw.startsWith('/data/') || raw.startsWith('/storage/') || raw.startsWith('/cache/')) {
    return DocumentType.legacyLocal;
  }
  // Strip URL query parameters for accurate extension detection on cloud URLs
  final clean = raw.split('?').first;
  if (clean.startsWith('data:image/') ||
      clean.endsWith('.jpg') ||
      clean.endsWith('.jpeg') ||
      clean.endsWith('.png') ||
      clean.endsWith('.webp')) {
    return DocumentType.image;
  }
  if (clean.startsWith('data:application/pdf') || clean.endsWith('.pdf')) {
    return DocumentType.pdf;
  }
  if (clean.startsWith('data:application/vnd.openxmlformats') ||
      clean.startsWith('data:application/msword') ||
      clean.endsWith('.docx') ||
      clean.endsWith('.doc')) {
    return DocumentType.word;
  }
  if (clean.startsWith('data:text/') || clean.endsWith('.txt')) {
    return DocumentType.text;
  }
  return DocumentType.unknown;
}

