  Future<void> _exportPdf(List<LeaveRequestModel> currentLeaves) async {
    if (currentLeaves.isEmpty) {
      ToastNotification.show(context, message: 'No leave request records available to export.', type: ToastType.warning);
      return;
    }

    final currentUser = ref.read(currentUserProvider);
    final sectorLabel = _selectedWorkAreaId == 'all'
        ? (currentUser.role == UserRole.supervisor ? (currentUser.assignedAreaName ?? 'Assigned Sectors') : 'All Ormoc Sectors')
        : _selectedWorkAreaId;

    try {
      final pdfBytes = await OfficialReportPdfHelper.generateLeavesPdf(
        leaves: currentLeaves,
        generatedBy: currentUser,
        dateRangeLabel: _getDateLabel(),
        sectorLabel: sectorLabel,
      );

      final filename = 'BantayGawa_LeaveAudit_${DateFormat('yyyyMMdd').format(DateTime.now())}.pdf';
      downloadBytes(
        filename: filename,
        bytes: pdfBytes,
        mimeType: 'application/pdf',
      );

      if (mounted) {
        ToastNotification.show(context, message: 'Official PDF downloaded ($filename).', type: ToastType.success);
      }
    } catch (e) {
      if (mounted) {
        ToastNotification.show(context, message: 'Failed to generate PDF: $e', type: ToastType.error);
      }
    }
  }

  void _promptDenialDialog(LeaveRequestModel req) {
    final reasonController = TextEditingController();

    ConfirmationDialog.show(
      context,
      title: 'Deny Leave Request',
      message: 'Please provide an official administrative reason for denying ${req.workerName}\'s leave request.',
      confirmLabel: 'Confirm Denial',
      confirmVariant: ButtonVariant.danger,
      contentWidget: Padding(
        padding: const EdgeInsets.only(top: 12),
        child: TextField(
          controller: reasonController,
          maxLines: 3,
          decoration: InputDecoration(
            hintText: 'e.g. Critical operational understaffing in sector...',
            border: OutlineInputBorder(borderRadius: BorderRadius.circular(8)),
            contentPadding: const EdgeInsets.all(12),
          ),
        ),
      ),
      onConfirm: () async {
        final reason = reasonController.text.trim();
        if (reason.isEmpty) {
          ToastNotification.show(context, message: 'Denial reason is mandatory.', type: ToastType.error);
          return false;
        }
        try {
          final currentUser = ref.read(currentUserProvider);
          await ref.read(dataRepositoryProvider).updateLeaveStatus(
                req.leaveId,
                'denied',
                adminId: currentUser.userId,
                rejectionReason: reason,
              );
          ref.invalidate(leaveRequestsProvider);
          if (mounted) {
            ToastNotification.show(context, message: 'Leave request denied with reason logged.', type: ToastType.info);
          }
          return true;
        } catch (e) {
          if (mounted) {
            ToastNotification.show(context, message: 'Failed to deny leave request: $e', type: ToastType.error);
          }
          return false;
        }
      },
    );
  }

