  @override
  Widget build(BuildContext context) {
    final currentUser = ref.watch(currentUserProvider);
    final leaveRequestsAsync = ref.watch(leaveRequestsProvider);
    final workAreasAsync = ref.watch(workAreasProvider);
    final rawLeaves = leaveRequestsAsync.value ?? [];
    final rawWorkAreas = workAreasAsync.value ?? [];
    final globalSearch = ref.watch(globalSearchProvider).toLowerCase();
    final workAreas = currentUser.role == UserRole.supervisor
        ? rawWorkAreas.where((a) =>
            a.supervisorId == currentUser.userId ||
            (a.supervisorName.isNotEmpty && a.supervisorName.toLowerCase() == currentUser.fullName.toLowerCase()) ||
            a.workareaId == currentUser.assignedAreaId ||
            a.name == currentUser.assignedAreaName).toList()
        : rawWorkAreas;
    final leaves = currentUser.role == UserRole.supervisor
        ? rawLeaves.where((l) {
            return workAreas.any((a) =>
                (l.workareaId != null && l.workareaId == a.workareaId) ||
                a.name.toLowerCase() == l.areaName.toLowerCase());
          }).toList()
        : rawLeaves;

    final totalCount = leaves.length;
    final pendingCount = leaves.where((l) => l.status.toLowerCase() == 'pending').length;
    final approvedCount = leaves.where((l) => l.status.toLowerCase() == 'approved').length;
    final deniedCount = leaves.where((l) => l.status.toLowerCase() == 'denied' || l.status.toLowerCase() == 'declined').length;

    final filteredLeaves = leaves.where((l) {
      // 1. Search filter
      final matchesSearch = l.workerName.toLowerCase().contains(globalSearch) ||
          l.type.toLowerCase().contains(globalSearch) ||
          l.reason.toLowerCase().contains(globalSearch) ||
          l.areaName.toLowerCase().contains(globalSearch) ||
          l.status.toLowerCase().contains(globalSearch);
      if (!matchesSearch) return false;

      // 2. Status filter
      final matchesStatus = _statusFilter == 'all' ||
          l.status.toLowerCase() == _statusFilter.toLowerCase() ||
          (_statusFilter == 'denied' && (l.status.toLowerCase() == 'declined' || l.status.toLowerCase() == 'denied'));
      if (!matchesStatus) return false;

      // 3. Work Area Sector Filter (for Admin)
      if (_selectedWorkAreaId != 'all') {
        final matchesArea = (l.workareaId != null && l.workareaId == _selectedWorkAreaId) ||
            workAreas.any((w) => w.workareaId == _selectedWorkAreaId && w.name.toLowerCase() == l.areaName.toLowerCase());
        if (!matchesArea) return false;
      }

      // 4. Date / Period Filter
      DateTime? parseDate(String d) {
        try {
          return DateTime.parse(d);
        } catch (_) {
          return null;
        }
      }

      // 4. Date / Period Filter (Strictly matches the date the request was submitted)
      final submissionDate = l.createdAt ?? parseDate(l.startDate);

      if (_dateRangePreset == 'week') {
        if (submissionDate == null) return false;
        final now = DateTime.now();
        final weekAgo = DateTime(now.year, now.month, now.day).subtract(const Duration(days: 7));
        final todayEnd = DateTime(now.year, now.month, now.day, 23, 59, 59);
        if (submissionDate.isBefore(weekAgo) || submissionDate.isAfter(todayEnd)) {
          return false;
        }
      } else if (_dateRangePreset == 'month') {
        if (submissionDate == null) return false;
        final now = DateTime.now();
        if (submissionDate.year != now.year || submissionDate.month != now.month) {
          return false;
        }
      } else if (_selectedDate != null) {
        if (submissionDate == null) return false;
        final matches = submissionDate.year == _selectedDate!.year &&
            submissionDate.month == _selectedDate!.month &&
            submissionDate.day == _selectedDate!.day;
        if (!matches) return false;
      }

      return true;
    }).toList();

    // Dynamic sorting
    switch (_sortBy) {
      case 'newest':
        filteredLeaves.sort((a, b) {
          final aDate = a.createdAt ?? DateTime.tryParse(a.startDate) ?? DateTime(1970);
          final bDate = b.createdAt ?? DateTime.tryParse(b.startDate) ?? DateTime(1970);
          final cmp = bDate.compareTo(aDate);
          if (cmp != 0) return cmp;
          return b.startDate.compareTo(a.startDate);
        });
        break;
      case 'oldest':
        filteredLeaves.sort((a, b) {
          final aDate = a.createdAt ?? DateTime.tryParse(a.startDate) ?? DateTime(1970);
          final bDate = b.createdAt ?? DateTime.tryParse(b.startDate) ?? DateTime(1970);
          final cmp = aDate.compareTo(bDate);
          if (cmp != 0) return cmp;
          return a.startDate.compareTo(b.startDate);
        });
        break;
      case 'pending_first':
        filteredLeaves.sort((a, b) {
          if (a.status == 'pending' && b.status != 'pending') return -1;
          if (a.status != 'pending' && b.status == 'pending') return 1;
          final aDate = a.createdAt ?? DateTime.tryParse(a.startDate) ?? DateTime(1970);
          final bDate = b.createdAt ?? DateTime.tryParse(b.startDate) ?? DateTime(1970);
          return bDate.compareTo(aDate);
        });
        break;
      case 'worker_name':
        filteredLeaves.sort((a, b) => a.workerName.toLowerCase().compareTo(b.workerName.toLowerCase()));
        break;
      case 'start_date':
        filteredLeaves.sort((a, b) {
          final aStart = DateTime.tryParse(a.startDate) ?? DateTime(1970);
          final bStart = DateTime.tryParse(b.startDate) ?? DateTime(1970);
          return bStart.compareTo(aStart);
