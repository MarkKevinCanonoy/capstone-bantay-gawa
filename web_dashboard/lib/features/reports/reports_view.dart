import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../../core/theme/app_colors.dart';
import '../../core/widgets/app_card.dart';
import '../../core/widgets/app_button.dart';
import '../../core/widgets/toast_notification.dart';
import '../../data/models/user_model.dart';
import '../../data/repositories/repository_provider.dart';

class ReportsView extends ConsumerStatefulWidget {
  const ReportsView({super.key});

  @override
  ConsumerState<ReportsView> createState() => _ReportsViewState();
}

class _ReportsViewState extends ConsumerState<ReportsView> {
  String _selectedReportType = 'attendance';
  String _selectedDateRange = 'week';
  String _selectedArea = 'all';

  void _exportPdf() async {
    final attendance = ref.read(attendanceProvider).value ?? [];
    final currentUser = ref.read(currentUserProvider);

    final pdf = pw.Document();
    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Header(
                level: 0,
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text('BantayGawa - Official Attendance Report', style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold)),
                        pw.Text('Environment and Natural Resources Office (ENRO) - Ormoc City', style: const pw.TextStyle(fontSize: 12)),
                      ],
                    ),
                    pw.Text('Generated: 2026-09-09', style: const pw.TextStyle(fontSize: 10)),
                  ],
                ),
              ),
              pw.SizedBox(height: 12),
              pw.Text('Generated by: ${currentUser.fullName} (${currentUser.roleDisplayName})', style: const pw.TextStyle(fontSize: 11)),
              pw.SizedBox(height: 16),
              pw.TableHelper.fromTextArray(
                headers: ['Worker Name', 'Work Area', 'Time In', 'Time Out', 'Face Match', 'Status'],
                data: attendance.map((log) => [
                  log.workerName,
                  log.areaName,
                  log.timeIn,
                  log.timeOut,
                  log.faceMatch ? 'Yes' : 'No',
                  log.isVerified ? 'Verified' : 'Unverified',
                ]).toList(),
              ),
            ],
          );
        },
      ),
    );

    await Printing.layoutPdf(onLayout: (PdfPageFormat format) async => pdf.save());
    if (mounted) {
      ToastNotification.show(context, message: 'PDF report generated for download/print.', type: ToastType.success);
    }
  }

  void _exportCsv() {
    final attendance = ref.read(attendanceProvider).value ?? [];
    final rows = [
      ['Attendance ID', 'Worker Name', 'Employee ID', 'Work Area', 'Time In', 'Time Out', 'Face Match', 'Verified'],
      ...attendance.map((log) => [
        log.attendanceId,
        log.workerName,
        log.workerEmpId,
        log.areaName,
        log.timeIn,
        log.timeOut,
        log.faceMatch ? 'TRUE' : 'FALSE',
        log.isVerified ? 'TRUE' : 'FALSE',
      ]),
    ];

    final csvString = rows.map((r) => r.map((c) => '"$c"').join(',')).join('\n');
    debugPrint('CSV Export Generated (${csvString.length} bytes)');

    ToastNotification.show(
      context,
      message: 'CSV exported successfully (${attendance.length} records processed).',
      type: ToastType.success,
    );
  }

  @override
  Widget build(BuildContext context) {
    final currentUser = ref.watch(currentUserProvider);
    final attendanceAsync = ref.watch(attendanceProvider);
    final attendance = attendanceAsync.value ?? [];

    return Padding(
      padding: const EdgeInsets.all(24),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text('Analytical Reports & Exports', style: TextStyle(fontSize: 22, fontWeight: FontWeight.w800, color: AppColors.textPrimary)),
                  const SizedBox(height: 4),
                  Text(
                    currentUser.role == UserRole.admin
                        ? 'Generate, preview, and download compliance audits across all Ormoc sectors.'
                        : 'Attendance summaries and worker logs scoped to your assigned work areas.',
                    style: const TextStyle(fontSize: 13, color: AppColors.textMuted),
                  ),
                ],
              ),
              Row(
                children: [
                  AppButton(
                    label: 'Export CSV / Excel',
                    icon: Icons.table_chart_outlined,
                    variant: ButtonVariant.secondary,
                    onPressed: _exportCsv,
                  ),
                  const SizedBox(width: 12),
                  AppButton(
                    label: 'Export Official PDF',
                    icon: Icons.picture_as_pdf_outlined,
                    variant: ButtonVariant.primary,
                    onPressed: _exportPdf,
                  ),
                ],
              ),
            ],
          ),
          const SizedBox(height: 20),

          // Filters Card
          AppCard(
            padding: const EdgeInsets.all(16),
            child: Row(
              children: [
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      const Text('Report Type', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppColors.textMuted)),
                      const SizedBox(height: 6),
                      DropdownButtonFormField<String>(
                        initialValue: _selectedReportType,
                        items: const [
                          DropdownMenuItem(value: 'attendance', child: Text('Attendance Log Summary')),
                          DropdownMenuItem(value: 'geofence', child: Text('Geofence Compliance Audit')),
                          DropdownMenuItem(value: 'credit', child: Text('Worker Credit Scores')),
                        ],
                        onChanged: (val) => setState(() => _selectedReportType = val!),
                        decoration: const InputDecoration(),
                      ),
                    ],
                  ),
                ),
                const SizedBox(width: 16),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      const Text('Date Horizon', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppColors.textMuted)),
                      const SizedBox(height: 6),
                      DropdownButtonFormField<String>(
                        initialValue: _selectedDateRange,
                        items: const [
                          DropdownMenuItem(value: 'today', child: Text('Today (Current Shift)')),
                          DropdownMenuItem(value: 'week', child: Text('Past 7 Days')),
                          DropdownMenuItem(value: 'month', child: Text('This Month (September 2026)')),
                        ],
                        onChanged: (val) => setState(() => _selectedDateRange = val!),
                        decoration: const InputDecoration(),
                      ),
                    ],
                  ),
                ),
                const SizedBox(width: 16),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      const Text('Work Area', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppColors.textMuted)),
                      const SizedBox(height: 6),
                      DropdownButtonFormField<String>(
                        initialValue: _selectedArea,
                        items: const [
                          DropdownMenuItem(value: 'all', child: Text('All Monitored Sectors')),
                          DropdownMenuItem(value: 'area-1', child: Text('Ormoc City Hall Zone')),
                          DropdownMenuItem(value: 'area-2', child: Text('Ormoc Public Market')),
                          DropdownMenuItem(value: 'area-3', child: Text('Ormoc Bus Terminal')),
                        ],
                        onChanged: (val) => setState(() => _selectedArea = val!),
                        decoration: const InputDecoration(),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 20),

          // Preview Table Header
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              const Text('REPORT PREVIEW DATA', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: AppColors.textMuted)),
              Text('Showing ${attendance.length} records ready for compilation', style: const TextStyle(fontSize: 12, color: AppColors.textMuted)),
            ],
          ),
          const SizedBox(height: 10),

          // Preview Table
          Expanded(
            child: AppCard(
              padding: EdgeInsets.zero,
              child: SingleChildScrollView(
                child: DataTable(
                  horizontalMargin: 20,
                  columnSpacing: 24,
                  columns: const [
                    DataColumn(label: Text('WORKER NAME', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('SECTOR', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('TIME-IN', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('TIME-OUT', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('GEOFENCE ACCURACY', style: TextStyle(fontWeight: FontWeight.bold))),
                    DataColumn(label: Text('AUDIT VERIFICATION', style: TextStyle(fontWeight: FontWeight.bold))),
                  ],
                  rows: attendance.map((log) {
                    return DataRow(
                      cells: [
                        DataCell(Text(log.workerName, style: const TextStyle(fontWeight: FontWeight.w600))),
                        DataCell(Text(log.areaName)),
                        DataCell(Text(log.timeIn)),
                        DataCell(Text(log.timeOut)),
                        DataCell(
                          Row(
                            children: [
                              Icon(
                                log.hasWarning ? Icons.cancel_outlined : Icons.check_circle_outline,
                                color: log.hasWarning ? AppColors.brightRed : Colors.green,
                                size: 16,
                              ),
                              const SizedBox(width: 6),
                              Text(log.hasWarning ? 'Out-of-Bounds' : '100% In-Zone'),
                            ],
                          ),
                        ),
                        DataCell(
                          Text(log.isVerified ? 'Verified by Supervisor' : 'Pending Audit', style: TextStyle(color: log.isVerified ? Colors.green : AppColors.warningText, fontWeight: FontWeight.w600)),
                        ),
                      ],
                    );
                  }).toList(),
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}
